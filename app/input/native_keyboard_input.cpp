#include "input/native_keyboard_input.h"

namespace scr::runtime {
std::optional<std::uint8_t> nativeAmigaRawKey(unsigned key,unsigned scan,bool extended){
    if(key>='1'&&key<='9')return std::uint8_t(key-'1'+1);
    if(key=='0')return 0x0a;
    if(key>=0x70&&key<=0x79)return std::uint8_t(0x50+key-0x70); // F1..F10
    switch(key){
    case 'Q':return 0x10;case 'W':return 0x11;case 'E':return 0x12;case 'R':return 0x13;
    case 'T':return 0x14;case 'Y':return 0x15;case 'U':return 0x16;case 'I':return 0x17;
    case 'O':return 0x18;case 'P':return 0x19;
    case 'A':return 0x20;case 'S':return 0x21;case 'D':return 0x22;case 'F':return 0x23;
    case 'G':return 0x24;case 'H':return 0x25;case 'J':return 0x26;case 'K':return 0x27;case 'L':return 0x28;
    case 'Z':return 0x31;case 'X':return 0x32;case 'C':return 0x33;case 'V':return 0x34;
    case 'B':return 0x35;case 'N':return 0x36;case 'M':return 0x37;
    case 0xc0:return 0x00;case 0xbd:return 0x0b;case 0xbb:return 0x0c;
    case 0xdc:return 0x0d;case 0xdb:return 0x1a;case 0xdd:return 0x1b;
    case 0xba:return 0x29;case 0xde:return 0x2a;case 0xe2:return 0x30;
    case 0xbc:return 0x38;case 0xbe:return 0x39;case 0xbf:return 0x3a;
    case 0x20:return 0x40;case 0x08:return 0x41;case 0x09:return 0x42;
    case 0x0d:return extended?0x43:0x44;
    case 0x1b:return 0x45;case 0x2e:return 0x46;
    case 0x26:return 0x4c;case 0x28:return 0x4d;case 0x27:return 0x4e;case 0x25:return 0x4f;
    case 0x10:return scan==0x36?0x61:0x60;
    case 0xa0:return 0x60;case 0xa1:return 0x61;
    case 0x14:return 0x62;case 0x11:case 0xa2:case 0xa3:return 0x63;
    case 0x12:return extended?0x65:0x64;case 0xa4:return 0x64;case 0xa5:return 0x65;
    case 0x5b:return 0x66;case 0x5c:return 0x67;
    case 0x60:return 0x0f;case 0x61:return 0x1d;case 0x62:return 0x1e;case 0x63:return 0x1f;
    case 0x64:return 0x2d;case 0x65:return 0x2e;case 0x66:return 0x2f;
    case 0x67:return 0x3d;case 0x68:return 0x3e;case 0x69:return 0x3f;case 0x6e:return 0x3c;
    default:return std::nullopt;
    }
}
}
